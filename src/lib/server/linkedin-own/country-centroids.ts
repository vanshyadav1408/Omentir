const CENTROIDS = new Map<string, [number, number]>(
  TABLE.split(" ").map((item) => {
    const [code, coords] = item.split(":");
    const [lat, lon] = coords.split(",").map(Number);
    return [code, [lat, lon]];
  }),
);

// Great-circle distance in km between two countries; Infinity when either
// is unknown, so unknown countries sort last.
export function countryDistanceKm(from: string, to: string) {
  if (from === to) return 0;
  const a = CENTROIDS.get(from);
  const b = CENTROIDS.get(to);
  if (!a || !b) return Infinity;
  const rad = Math.PI / 180;
  const dLat = (b[0] - a[0]) * rad;
  const dLon = (b[1] - a[1]) * rad;
  const h = Math.sin(dLat / 2) ** 2 + Math.cos(a[0] * rad) * Math.cos(b[0] * rad) * Math.sin(dLon / 2) ** 2;
  return 2 * 6371 * Math.asin(Math.min(1, Math.sqrt(h)));
}
